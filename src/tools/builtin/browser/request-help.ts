// ============================================
// 交互工具:request_help(暂停并把控制权交回用户)
// ============================================
//
// 这是**唯一**需要「跨出执行单元」的能力,也是它存在的全部理由(判据②):
// 代码块是原子的 —— 一段代码跑完才返回,中间没有「跟用户说句话然后等他」的位置。
// 模型自己在代码里写 `page.wait_for_url(...)` 会死等,期间 agent 卡住、
// 用户还看不到任何提示。
//
// 所以它**不碰浏览器**:导航、定位登录入口、点击一律由模型写代码做 ——
// 模型有 a11y 快照和视觉能力,能按站点差异自己找入口,而框架只能靠关键词
// 和 CSS 猜(第一版就是这么写的,和架构里「浏览器是代码里的一个库」直接矛盾)。
//
// 命名从 request_login 改成 request_help,因为登录只是场景之一:
// 验证码、人机检测、二次验证、扫码,本质都是「需要人操作一下」。
// 按机制命名而非按场景命名,才不会每加一种情况就要新工具。
// ============================================

import { z } from 'zod';
import { Tool, ToolContext, ToolResult } from '../../contract.js';

export class RequestHelpTool implements Tool {
  name = 'request_help';

  description = [
    '暂停任务,请用户在浏览器窗口里手动操作一下,然后立即返回(不阻塞等待)。',
    '',
    '什么时候用 —— 只在**你无法自动完成、必须由人做**的时候:',
    '  · 登录(账号密码只能用户自己输)',
    '  · 验证码、滑块、人机检测',
    '  · 二次验证、扫码确认',
    '  · 需要用户在页面上做选择或授权',
    '',
    '什么时候**不要**用:页面能自己点、能自己填的一律写代码做。',
    '这个工具每次都会打断用户,滥用会很烦人。',
    '',
    '前置:请先用 execute_python 把浏览器开到需要操作的那个页面',
    '(比如已经点进登录页)。本工具不做导航 —— 定位入口、点击都由你写代码完成,',
    '你有 aria_snapshot 和截图,比框架猜选择器准。',
    '',
    '调用后:',
    '① 明确告诉用户要做什么、以及**请他切换到浏览器窗口**',
    '   (窗口不会自动弹到他面前,这是系统限制);',
    '② 等他回复「好了」之后,用 screenshot 确认状态再继续。',
    '',
    '绝不要在代码里填写账号密码 —— 那会把明文凭证写进对话记录。',
  ].join('\n');

  parameters = z.object({
    what_to_do: z
      .string()
      .min(1)
      .describe('请用户做什么。写清楚、可执行，会直接展示给他，例如「在浏览器里登录百度账号」'),
    why: z
      .string()
      .optional()
      .describe('为什么需要他介入。让用户知道自己在授权什么'),
  });

  // 不需要任何执行器：它只是把请求回流给模型、让模型转告用户。
  // 这也是它比 request_login 更通用的地方 —— 将来非浏览器场景同样能用
  needs = [] as const;

  // 不算危险：它不做任何实际操作，只是打断一次
  danger = false;

  async run(
    args: { what_to_do: string; why?: string },
    ctx: ToolContext,
  ): Promise<ToolResult> {
    ctx.logger.info('请求用户介入', {
      what_to_do: args.what_to_do,
      why: args.why,
    });

    return {
      ok: true,
      data: {
        acknowledged: true,
        what_to_do: args.what_to_do,
        ...(args.why ? { why: args.why } : {}),
        note:
          '已记录。现在请你（模型）做两件事：' +
          '① 直接告诉用户需要他做什么，并明确说「请切换到浏览器窗口」' +
          '——窗口不会自动弹出，不说他就不知道该去哪操作；' +
          '② 本轮就结束回答，等用户回复完成后再用 screenshot 确认状态。' +
          '不要在这一轮继续调用工具去轮询或等待。',
      },
    };
  }
}
